// สถานะล่าสุดจาก snapshot: มี session ที่รอคนตอบหรือพังอยู่ไหม
//
// ปลุกเฉพาะ *ขอบขาขึ้น* ไม่ใช่ตลอดเวลาที่ยังรอ — "เพิ่งมีเรื่องเกิดขึ้น" คือข่าว
// ส่วน "ยังรออยู่เหมือนเดิม" ไม่ใช่ และไฟ RGB รับหน้าที่บอกอันหลังไปแล้ว
void ct_dim_attention(bool needs_person);

// เดินนาฬิกาและสั่งไฟหลัง เรียกจากลูปหลัก
void ct_dim_tick(int elapsed_ms);
