// จอตอบว่า "เกิดอะไรขึ้นบ้าง" ซึ่งต้องหันไปอ่าน ส่วนไฟตอบคำถามเดียว:
// "ต้องลุกไปทำอะไรไหม" คำถามนั้นต้องตอบได้โดยไม่ต้องหันหน้า ไฟจึงไม่พยายาม
// บอกอะไรมากกว่าหนึ่งอย่าง
